import { useEffect, useRef, useState, type KeyboardEvent } from 'react';

export interface SearchResult {
  href: string;
  title: string;
  /** Section or page context, shown on the right. */
  context: string;
  /** Excerpt with <mark> around matches (Pagefind output for this site's own pages). */
  excerpt?: string;
  mono?: boolean;
}

/** Search backend. The site uses Pagefind; stories pass a fake. */
export type SearchFn = (query: string) => Promise<SearchResult[]>;

interface PagefindResult { data(): Promise<{ url: string; meta: { title?: string; section?: string; mono?: string }; excerpt: string; sub_results?: { title: string; url: string; excerpt: string }[] }> }
interface Pagefind { search(q: string): Promise<{ results: PagefindResult[] }>; init?(): Promise<void> }

let pagefind: Promise<Pagefind> | undefined;
/** Pagefind is generated by `npm run build`; it does not exist in `astro dev`. */
export const pagefindSearch: SearchFn = async (q) => {
  // The path is built at runtime so Vite does not try to bundle the generated index.
  const path = ['/pagefind', 'pagefind.js'].join('/');
  pagefind ??= import(/* @vite-ignore */ path) as Promise<Pagefind>;
  const pf = await pagefind;
  const { results } = await pf.search(q);
  const data = await Promise.all(results.slice(0, 8).map((r) => r.data()));
  return data.flatMap((d) => {
    const page = { href: d.url, title: d.meta.title ?? d.url, context: d.meta.section ?? '', excerpt: d.excerpt, mono: !!d.meta.mono };
    const subs = (d.sub_results ?? []).filter((s) => s.url !== d.url && s.title !== page.title).slice(0, 2)
      .map((s) => ({ href: s.url, title: s.title, context: '§ ' + page.title, excerpt: s.excerpt }));
    return [page, ...subs];
  }).slice(0, 10);
};

export interface SearchDialogProps {
  /** Shown before the reader types. */
  suggested: SearchResult[];
  search?: SearchFn;
  /** Open on mount (stories, tests). */
  defaultOpen?: boolean;
}

/**
 * Search, opened with ⌘K / Ctrl+K or any `[data-search-open]` button. A native modal <dialog>:
 * focus stays inside, Escape closes it. Results are a listbox driven by the arrow keys.
 */
export function SearchDialog({ suggested, search = pagefindSearch, defaultOpen = false }: SearchDialogProps) {
  const dialog = useRef<HTMLDialogElement>(null);
  const input = useRef<HTMLInputElement>(null);
  const [q, setQ] = useState('');
  const [results, setResults] = useState<SearchResult[]>(suggested);
  const [sel, setSel] = useState(0);
  const [state, setState] = useState<'idle' | 'loading' | 'unavailable'>('idle');

  const open = () => {
    const d = dialog.current;
    if (!d || d.open) return;
    setQ(''); setResults(suggested); setSel(0);
    d.showModal();
    input.current?.focus();
  };
  useEffect(() => {
    const onKey = (e: globalThis.KeyboardEvent) => {
      if ((e.metaKey || e.ctrlKey) && e.key.toLowerCase() === 'k') { e.preventDefault(); open(); }
    };
    const onClick = (e: MouseEvent) => {
      if ((e.target as Element | null)?.closest?.('[data-search-open]')) { e.preventDefault(); open(); }
    };
    window.addEventListener('keydown', onKey);
    document.addEventListener('click', onClick);
    if (defaultOpen || location.hash === '#search') open();
    return () => { window.removeEventListener('keydown', onKey); document.removeEventListener('click', onClick); };
  }, []);

  useEffect(() => {
    const t = q.trim();
    if (!t) { setResults(suggested); setState('idle'); return; }
    let live = true;
    setState('loading');
    const timer = setTimeout(() => {
      search(t).then((r) => { if (live) { setResults(r); setSel(0); setState('idle'); } }, () => { if (live) { setResults([]); setState('unavailable'); } });
    }, 80);
    return () => { live = false; clearTimeout(timer); };
  }, [q]);

  const close = () => dialog.current?.close();
  const go = (r: SearchResult | undefined) => { if (r) { close(); location.href = r.href; } };
  const onKey = (e: KeyboardEvent) => {
    if (e.key === 'ArrowDown') { e.preventDefault(); setSel((s) => Math.min(results.length - 1, s + 1)); }
    if (e.key === 'ArrowUp') { e.preventDefault(); setSel((s) => Math.max(0, s - 1)); }
    if (e.key === 'Enter') { e.preventDefault(); go(results[sel]); }
    if (e.key === 'Escape') { e.preventDefault(); close(); }
  };
  const empty = !q.trim();
  const active = results[sel] ? `search-option-${sel}` : undefined;

  return (
    <dialog
      ref={dialog}
      aria-label="Search documentation"
      onClick={(e) => { if (e.target === dialog.current) close(); }}
      className="search-dialog mx-auto mt-[10vh] w-[min(680px,calc(100%-24px))] overflow-hidden rounded-dialog border border-ink bg-paper p-0 text-ink shadow-overlay backdrop:bg-[oklch(0.21_0.01_80/0.28)]"
    >
      <div className="flex items-center gap-2.5 border-b border-line px-3.5">
        <input
          ref={input}
          type="search"
          value={q}
          onChange={(e) => setQ(e.target.value)}
          onKeyDown={onKey}
          placeholder="Search pages, APIs and sections"
          aria-label="Search"
          role="combobox"
          aria-expanded="true"
          aria-controls="search-results"
          aria-activedescendant={active}
          aria-autocomplete="list"
          className="h-14 min-w-0 flex-1 border-0 bg-transparent text-[17px] outline-none [&::-webkit-search-cancel-button]:hidden"
        />
        <button type="button" onClick={close} className="rounded-tag border border-line bg-transparent px-1.5 py-0.5 font-mono text-[11px] text-ink-2">esc</button>
      </div>
      <div id="search-results" role="listbox" aria-label={empty ? 'Suggested pages' : 'Results'} className="max-h-[min(460px,60vh)] overflow-auto p-1.5">
        {empty && <div className="px-3 pt-2 pb-1 font-mono text-tag text-mute" aria-hidden="true">Suggested</div>}
        {results.map((r, i) => (
          <a
            key={r.href + i}
            id={`search-option-${i}`}
            href={r.href}
            role="option"
            aria-selected={i === sel}
            onMouseEnter={() => setSel(i)}
            onClick={close}
            className={`flex flex-col gap-[3px] rounded-block px-3 py-2.5 no-underline ${i === sel ? 'bg-option' : ''}`}
          >
            <span className="flex items-baseline justify-between gap-3">
              <span className={r.mono ? 'font-mono text-ui font-semibold text-rx' : 'text-note font-semibold'}>{r.title}</span>
              <span className="font-mono text-tag whitespace-nowrap text-mute">{r.context}</span>
            </span>
            {r.excerpt && (
              <span
                className="block truncate text-sm leading-[1.45] text-ink-2 [&_mark]:bg-transparent [&_mark]:font-semibold [&_mark]:text-ink"
                dangerouslySetInnerHTML={{ __html: r.excerpt }}
              />
            )}
          </a>
        ))}
        {!empty && state === 'idle' && results.length === 0 && (
          <div className="px-3 py-[18px] text-base leading-normal text-ink-2">No results for “{q}”. Try a function name such as state or when, or browse the <a href="/docs/reference/" onClick={close}>API Reference</a>.</div>
        )}
        {state === 'unavailable' && (
          <div role="status" className="px-3 py-[18px] text-base leading-normal text-ink-2">The search index is created by <code className="font-mono text-[0.9em]">npm run build</code>. It is not available in the dev server.</div>
        )}
      </div>
      <div className="flex gap-4 border-t border-line px-3.5 py-2 font-mono text-[11px] text-mute" aria-hidden="true">
        <span>↑↓ move</span><span>↵ open</span><span>esc close</span>
      </div>
    </dialog>
  );
}

